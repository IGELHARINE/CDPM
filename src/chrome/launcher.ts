import fs from 'node:fs';
import path from 'node:path';
import { probe, type VersionInfo } from '../cdp/targets.js';
import { CdpmError } from '../errors.js';
import { spawnOrphan } from '../orphan.js';
import { paths, readConfig } from '../paths.js';
import { colorOf, hexToRgb, portOf } from '../slots.js';
import { pidAlive, sleep } from '../util.js';
import { findChrome } from './finder.js';
import { proxyArgs, type ProxySpec } from './proxy.js';

const READY_TIMEOUT_MS = 30_000;

export interface LaunchOptions {
  /** 창 없이 실행. 인자는 `--headless` 하나만 더한다. */
  headless?: boolean;
  /** 켜자마자 열 주소 (없으면 빈 탭) */
  url?: string;
  /** 사용자가 프록시를 써 달라고 했을 때만. 없으면 프록시 관련 인자를 하나도 넣지 않는다. */
  proxy?: ProxySpec;
}

export function chromeArgs(slot: number, opts: LaunchOptions = {}): string[] {
  const config = readConfig();
  return [
    `--remote-debugging-port=${portOf(slot)}`,
    `--user-data-dir=${paths.profile(slot)}`,
    '--no-first-run',
    '--no-default-browser-check',
    `--window-name=${slot}번`,
    // 창(탭 줄·툴바)을 슬롯 색으로 물들인다 → 어느 탭이든 창 색만 보면 몇 번 슬롯인지 안다 (작업표시줄 아이콘·상태줄과 같은 색).
    // Chrome 자체의 테마 기능이라 페이지는 알 수 없고 페이지 내용도 바뀌지 않는다. config.json의 slotTheme: false로 끈다.
    ...(!opts.headless && config.slotTheme !== false ? [`--install-autogenerated-theme=${hexToRgb(colorOf(slot)).join(',')}`] : []),
    // Google 계정 동기화를 끈다. 슬롯에서 구글에 로그인하면 계정의 테마가 내려와 슬롯 색을 덮고, 확장 프로그램(광고 차단 등)이
    // 따라 설치돼 페이지를 바꾼다. 사이트 로그인(쿠키)은 프로필에 그대로 남는다. config.json의 sync: true로 켠다.
    ...(config.sync === true ? [] : ['--disable-sync']),
    ...(opts.headless ? ['--headless'] : []),
    ...(config.extraArgs ?? []),
  ];
}

/**
 * 프로필에 계정 테마(동기화로 내려온 Chrome 웹 스토어 테마)가 남아 있으면 걷어 낸다. 그런 테마가 깔려 있으면
 * --install-autogenerated-theme이 먹지 않아 슬롯 색이 나오지 않는다 (동기화를 끈 뒤에도 프로필에 남는다).
 * Chrome이 꺼져 있을 때(켜기 직전)만 프로필의 Preferences를 고친다. 실패하면 그대로 둔다.
 */
export function clearForeignTheme(profileDir: string): boolean {
  const file = path.join(profileDir, 'Default', 'Preferences');
  try {
    const prefs = JSON.parse(fs.readFileSync(file, 'utf8')) as { extensions?: { theme?: { id?: string } }; browser?: { theme?: Record<string, unknown> } };
    const id = prefs.extensions?.theme?.id;
    if (!id || id === 'autogenerated_theme_id') return false;
    delete prefs.extensions!.theme;
    if (prefs.browser?.theme) delete prefs.browser.theme.saved_local_theme;
    const tmp = `${file}.cdpm-tmp-${process.pid}`;
    fs.writeFileSync(tmp, JSON.stringify(prefs));
    fs.renameSync(tmp, file);
    return true;
  } catch {
    return false;
  }
}

export interface Launched {
  pid: number | undefined;
  version: VersionInfo;
}

/**
 * 슬롯 Chrome을 띄우고 CDP가 응답할 때까지 기다린다. CDPM·Claude Code·VS Code가 끝나도(줄기째 강제 종료돼도)
 * Chrome은 살아 있도록 부모 없는 프로세스로 띄운다 (orphan.ts).
 */
export async function launchChrome(slot: number, opts: LaunchOptions = {}): Promise<Launched> {
  // 시작 주소는 Chrome 실행 인자 끝에 붙는다. '-'로 시작하면 주소가 아니라 Chrome 옵션으로 읽힌다.
  if (opts.url && /^\s*-/.test(opts.url)) throw new CdpmError(`Not a URL: ${opts.url.slice(0, 80)}`);
  const chrome = findChrome();
  fs.mkdirSync(paths.profile(slot), { recursive: true });
  if (!opts.headless && readConfig().slotTheme !== false) clearForeignTheme(paths.profile(slot));
  const extra = opts.proxy ? await proxyArgs(slot, opts.proxy) : [];
  let pid: number;
  try {
    ({ pid } = await spawnOrphan(chrome, [...chromeArgs(slot, opts), ...extra, opts.url || 'about:blank'], { hide: false }));
  } catch (e) {
    throw new CdpmError(`Failed to launch Chrome: ${(e as Error).message}`);
  }

  const deadline = Date.now() + READY_TIMEOUT_MS;
  while (Date.now() < deadline) {
    const p = await probe(slot, 2000);
    if (p.state === 'chrome') return { pid, version: p.version };
    if (!pidAlive(pid)) {
      throw new CdpmError(
        `Slot ${slot} Chrome exited right after launch. ` +
        `If a Chrome using the same profile (${paths.profile(slot)}) is already running without a debugging port, the new one hands its window over and exits. Close that window and launch again.`,
      );
    }
    await sleep(100);
  }
  throw new CdpmError(
    `Slot ${slot} Chrome started, but CDP port ${portOf(slot)} did not open within ${READY_TIMEOUT_MS / 1000}s. ` +
    `A Chrome using the same profile (${paths.profile(slot)}) may already be running without a debugging port. Close it and try again.`,
  );
}
